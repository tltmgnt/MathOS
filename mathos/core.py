"""
MathOS Core — Unified AI Reasoning System.

Combines mathematical verification, multi-agent
coordination, and AI-powered general reasoning.
"""

from dataclasses import asdict, dataclass, field
from typing import List

from mathos.agents import MultiAgentMathOS
from mathos.ai_engine import AIEngine


@dataclass
class ReasoningResult:
    problem: str
    domain: str
    answer: str
    explanation: str
    verification_status: str = "unverified"
    evidence: List[str] = field(default_factory=list)

    def to_dict(self):
        return asdict(self)


class MathOS:
    """Unified MathOS reasoning interface."""

    SUPPORTED_DOMAINS = {
        "mathematics",
        "science",
        "coding",
        "research",
        "general",
    }

    def __init__(self, ai_engine=None):
        self.multi_agent = MultiAgentMathOS()
        self.ai_engine = (
            ai_engine if ai_engine is not None
            else AIEngine()
        )

    def solve(self, problem: str, domain: str = "general"):
        if not isinstance(problem, str) or not problem.strip():
            raise ValueError(
                "Problem must be a nonempty string."
            )

        if domain not in self.SUPPORTED_DOMAINS:
            raise ValueError(
                f"Unsupported domain: {domain}"
            )

        problem = problem.strip()

        if domain == "mathematics":
            result = self.multi_agent.solve(problem)

            return ReasoningResult(
                problem=problem,
                domain=domain,
                answer=result["answer"],
                explanation=(
                    "A deterministic solver calculated the answer. "
                    "The critic checked its metadata, and the "
                    "verifier recomputed the equation."
                ),
                verification_status=result["status"],
                evidence=[
                    f"Critic: {result['critic']['status']}",
                    f"Verifier: {result['verifier']['status']}",
                    "Scope: supported linear equations",
                ],
            )

        result = self.ai_engine.solve(
            problem,
            domain=domain,
        )

        return ReasoningResult(
            problem=problem,
            domain=domain,
            answer=result["answer"],
            explanation=(
                "Generated by an AI model. "
                "Independent verification has not been performed."
            ),
            verification_status="unverified",
            evidence=[
                f"Model: {result['model']}",
                "Verification: AI-generated response only",
            ],
        )


if __name__ == "__main__":
    system = MathOS()

    result = system.solve(
        "2x + 5 = 13",
        domain="mathematics",
    )

    print(result.to_dict())
